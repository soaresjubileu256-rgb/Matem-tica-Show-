// ordem embaralhada fixa (todo mundo vê a mesma frase no mesmo dia)
const DAILY_QUOTE_ORDER = (()=>{
  const idx = DAILY_QUOTES.map((_, i)=> i);
  let seed = 20261029;
  const rnd = ()=>{ seed = (seed*1103515245 + 12345) % 2147483648; return seed/2147483648; };
  for(let i = idx.length-1; i>0; i--){ const j = Math.floor(rnd()*(i+1)); [idx[i], idx[j]] = [idx[j], idx[i]]; }
  return idx;
})();

function dailyQuote(date){
  const d = date || new Date();
  const day = Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 864e5);
  return DAILY_QUOTES[DAILY_QUOTE_ORDER[day % DAILY_QUOTES.length]];
}

function dailyQuoteCard(){
  const q = dailyQuote();
  const card = h(`<div class="card dq-card">
    <div class="dq-head"><span class="dq-ico">💬</span><b>Frase do dia</b><button type="button" class="dq-say" aria-label="Ouvir a frase">🔊</button></div>
    <p class="dq-text"></p>
  </div>`);
  card.querySelector('.dq-text').textContent = q;
  card.querySelector('.dq-say').onclick = ()=> speak(q);
  return card;
}
